<script>
(function ($) {
    function initPlansSlider() {
        var $slider = $('.plans-slider');
        if (!$slider.length || typeof $.fn.slick !== 'function') {
            return;
        }
        if ($slider.hasClass('slick-initialized')) {
            $slider.slick('setPosition');
            return;
        }
        $slider.slick({
            slidesToShow: 3,
            slidesToScroll: 1,
            autoplay: false,
            speed: 300,
            arrows: true,
            dots: false,
            infinite: true,
            prevArrow: '.plans-arrows .arrow-left',
            nextArrow: '.plans-arrows .arrow-right',
            responsive: [
                { breakpoint: 992, settings: { slidesToShow: 2, slidesToScroll: 1 } },
                { breakpoint: 576, settings: { slidesToShow: 1, slidesToScroll: 1 } }
            ]
        });
    }

    $(function () {
        initPlansSlider();
        setTimeout(initPlansSlider, 200);
        setTimeout(initPlansSlider, 600);
    });
    $(window).on('load', function () {
        initPlansSlider();
        if ($('.plans-slider').hasClass('slick-initialized')) {
            $('.plans-slider').slick('setPosition');
        }
    });
})(jQuery);
</script>
@endpush

